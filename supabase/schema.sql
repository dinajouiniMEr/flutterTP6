-- Safe to run on the Workshop 4 clients table. Existing integer `id` values
-- remain intact; client_uuid is the stable UUID used for offline upserts.
create table if not exists public.clients (
  id bigint generated by default as identity primary key,
  client_uuid uuid not null unique default gen_random_uuid(),
  name text not null,
  lat double precision,
  lng double precision,
  location_accuracy_m double precision,
  location_captured_at timestamptz,
  created_at timestamptz not null default now()
);

alter table public.clients
  add column if not exists client_uuid uuid default gen_random_uuid(),
  add column if not exists lat double precision,
  add column if not exists lng double precision,
  add column if not exists location_accuracy_m double precision,
  add column if not exists location_captured_at timestamptz,
  add column if not exists created_at timestamptz default now();

update public.clients set client_uuid = gen_random_uuid() where client_uuid is null;
update public.clients set created_at = now() where created_at is null;
alter table public.clients alter column client_uuid set not null;
alter table public.clients alter column client_uuid set default gen_random_uuid();
alter table public.clients alter column created_at set not null;
alter table public.clients alter column created_at set default now();
create unique index if not exists clients_client_uuid_key on public.clients (client_uuid);

alter table public.clients enable row level security;
grant select, insert, update, delete on public.clients to authenticated;

drop policy if exists "Authenticated users can read clients" on public.clients;
create policy "Authenticated users can read clients" on public.clients
  for select to authenticated using (true);
drop policy if exists "Authenticated users can add clients" on public.clients;
create policy "Authenticated users can add clients" on public.clients
  for insert to authenticated with check (true);
drop policy if exists "Authenticated users can update clients" on public.clients;
create policy "Authenticated users can update clients" on public.clients
  for update to authenticated using (true) with check (true);
drop policy if exists "Authenticated users can remove clients" on public.clients;
create policy "Authenticated users can remove clients" on public.clients
  for delete to authenticated using (true);

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'clients'
  ) then
    alter publication supabase_realtime add table public.clients;
  end if;
end
$$;
